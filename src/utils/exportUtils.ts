/**
 * Generates CycloneDX v1.5 compliant SBOM (Software Bill of Materials) JSON.
 */
export function generateCycloneDX_SBOM(report: PublicScanReport): string {
  const sbom = {
    bomFormat: 'CycloneDX',
    specVersion: '1.5',
    serialNumber: `urn:uuid:${report.scan_id}`,
    version: 1,
    metadata: {
      timestamp: report.scanned_at,
      tools: [
        {
          vendor: 'DependencyCheck Security',
          name: 'DependencyCheck AST Scanner',
          version: '1.0.0'
        }
      ],
      component: {
        type: 'application',
        name: report.project_name,
        version: '1.0.0'
      }
    },
    components: report.dependencies.map(d => ({
      type: 'library',
      name: d.package_name,
      version: d.current_version,
      purl: `pkg:${d.ecosystem}/${d.package_name}@${d.current_version}`,
      properties: [
        { name: 'dependencycheck:status', value: d.status },
        { name: 'dependencycheck:reachability', value: d.reachability },
        { name: 'dependencycheck:recommended_fix', value: d.recommended_fix || 'none' }
      ]
    })),
    vulnerabilities: report.findings.map(f => ({
      id: f.id,
      source: { name: 'OSV.dev / NVD / GitHub Advisory' },
      ratings: [
        {
          score: f.cvss,
          severity: f.severity.toLowerCase(),
          method: 'CVSSv31'
        }
      ],
      description: f.title,
      analysis: {
        state: f.reachability === 'reachable' ? 'exploitable' : 'not_affected',
        justification: f.reachability === 'reachable' 
          ? 'requires_dependency' 
          : 'code_not_reachable'
      },
      affects: [
        {
          ref: `pkg:npm/${f.package}`
        }
      ]
    }))
  };

  return JSON.stringify(sbom, null, 2);
}

/**
 * Generates SPDX 2.3 compliant SBOM JSON.
 */
export function generateSPDX_SBOM(report: PublicScanReport): string {
  const spdx = {
    spdxVersion: 'SPDX-2.3',
    dataLicense: 'CC0-1.0',
    SPDXID: 'SPDXRef-DOCUMENT',
    name: report.project_name,
    documentNamespace: `https://dependencycheck.io/spdx/${report.scan_id}`,
    creationInfo: {
      creators: ['Tool: DependencyCheck-AST-Engine-1.0'],
      created: report.scanned_at
    },
    packages: report.dependencies.map((d, idx) => ({
      SPDXID: `SPDXRef-Package-${idx + 1}-${d.package_name}`,
      name: d.package_name,
      versionInfo: d.current_version,
      downloadLocation: 'NOASSERTION',
      filesAnalyzed: false,
      licenseConcluded: 'NOASSERTION',
      licenseDeclared: 'NOASSERTION',
      externalRefs: [
        {
          referenceCategory: 'PACKAGE-MANAGER',
          referenceType: 'purl',
          referenceLocator: `pkg:${d.ecosystem}/${d.package_name}@${d.current_version}`
        }
      ]
    }))
  };

  return JSON.stringify(spdx, null, 2);
}
